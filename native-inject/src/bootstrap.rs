//! Reads the on-disk configuration the payload needs before it can rewrite a reply.
//!
//! The injected library gets no arguments: `entry` is called by the injector with a `dlopen`
//! handle and nothing else. Everything it needs therefore has to come off the module's data
//! directory, which the daemon and the app already own:
//!
//! * `keybox.xml` -- the certificates and private key the leaf is re-signed with. Optional: no
//!   keybox means no rewriting, and the hook then forwards every reply untouched. That is the
//!   correct failure mode, because a `generateKey` reply that still describes the real device is
//!   merely unattested, while a reply signed with a half-read key would be a broken parcel in the
//!   system keystore.
//! * `tee_status` -- the daemon's probe of the real TEE, written as `key=value` lines by
//!   `render`. It carries `boot_key`, `boot_hash` and `os_version`, which is exactly the
//!   attestation state the forged chain has to claim. Reading it keeps the payload and the
//!   daemon in agreement without inventing a second config language.
//! * `boot_key` -- the persisted fallback used when the probe could not read the AVB key. Same
//!   file the daemon generates on first boot, hex encoded.
//!
//! Anything missing or malformed degrades to the default instead of failing the load: the
//! process this runs in is `keystore2`, and refusing to install the hook because one hex digit
//! was wrong would trade a cosmetic problem for a non-booting key store.

use std::path::Path;

use crate::surgeon::RuntimeConfig;

/// Directory the module keeps its configuration in. Mirrors `certgen::config::CONFIG_PATH`.
pub const CONFIG_DIR: &str = "/data/adb/tricky_store";

/// Keybox file name, as written by the app.
pub const KEYBOX_FILE: &str = "keybox.xml";

/// The daemon's probe report, one `key=value` per line.
pub const TEE_STATUS_FILE: &str = "tee_status";

/// Hex-encoded 32-byte boot key, generated by the daemon when AVB did not expose one.
pub const BOOT_KEY_FILE: &str = "boot_key";

/// Loads the configuration from the module directory and installs it.
///
/// Returns `false` when there is no usable keybox, in which case the hook stays a pass-through.
pub fn install_default() -> bool {
    install(Path::new(CONFIG_DIR))
}

/// Loads the configuration from `dir` and installs it. Returns `false` if nothing was installed.
pub fn install(dir: &Path) -> bool {
    match load(dir) {
        Some(config) => crate::surgeon::install(config),
        None => false,
    }
}

/// Builds a [`RuntimeConfig`] from `dir`, or `None` when the keybox is missing or unusable.
pub fn load(dir: &Path) -> Option<RuntimeConfig> {
    let xml = std::fs::read_to_string(dir.join(KEYBOX_FILE)).ok()?;
    let mut config = RuntimeConfig::from_keybox_xml(&xml)?;
    if let Ok(text) = std::fs::read_to_string(dir.join(TEE_STATUS_FILE)) {
        apply_tee_status(&mut config, &text);
    }
    // Only consult the persisted key when the probe did not supply one: the probe read the real
    // AVB key, the file is a random stand-in generated when it could not.
    if is_unset(&config.boot_key) {
        if let Some(key) = read_hex_file(&dir.join(BOOT_KEY_FILE)) {
            config.boot_key = key;
        }
    }
    Some(config)
}

/// Applies the fields of a `tee_status` report that the surgery cares about.
///
/// Unknown keys are ignored on purpose: the report also carries the KeyMint version pair and the
/// module hash, which the payload has no use for, and a newer daemon adding a field must not make
/// an older payload reject the whole file.
pub fn apply_tee_status(config: &mut RuntimeConfig, text: &str) {
    for line in text.lines() {
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let value = value.trim();
        match key.trim() {
            "boot_key" => {
                if let Some(bytes) = from_hex(value) {
                    if !is_unset(&bytes) {
                        config.boot_key = bytes;
                    }
                }
            }
            "boot_hash" => {
                if let Some(bytes) = from_hex(value) {
                    if !is_unset(&bytes) {
                        config.boot_hash = bytes;
                    }
                }
            }
            "os_version" => {
                // `0` is what the probe writes when it could not parse the record; keeping the
                // default is better than stamping every attestation with Android 0.
                if let Ok(parsed) = value.parse::<i32>() {
                    if parsed > 0 {
                        config.os_version = parsed;
                    }
                }
            }
            _ => {}
        }
    }
}

/// Reads a hex-encoded blob from `path`, accepting only a non-empty result.
fn read_hex_file(path: &Path) -> Option<Vec<u8>> {
    let text = std::fs::read_to_string(path).ok()?;
    let bytes = from_hex(text.trim())?;
    if is_unset(&bytes) {
        return None;
    }
    Some(bytes)
}

/// True for an absent value: empty, or all zeroes.
///
/// All zeroes counts as absent because that is exactly the placeholder a missing digest decodes
/// to, and because a 32-byte `verifiedBootKey` of zeroes is the value the forged chain already
/// defaults to.
fn is_unset(bytes: &[u8]) -> bool {
    bytes.is_empty() || bytes.iter().all(|byte| *byte == 0)
}

/// Decodes an even-length hex string. Returns `None` on any malformed digit.
fn from_hex(text: &str) -> Option<Vec<u8>> {
    if text.is_empty() || !text.len().is_multiple_of(2) {
        return None;
    }
    let mut out = Vec::with_capacity(text.len() / 2);
    let bytes = text.as_bytes();
    // `as_chunks` is the total form of `chunks_exact`; the remainder is empty because the length
    // was checked above, and the assertion makes that dependency explicit instead of implicit.
    let (pairs, remainder) = bytes.as_chunks::<2>();
    debug_assert!(
        remainder.is_empty(),
        "even length leaves no single byte behind"
    );
    for pair in pairs {
        let high = hex_digit(pair[0])?;
        let low = hex_digit(pair[1])?;
        out.push((high << 4) | low);
    }
    Some(out)
}

/// One hex digit, or `None` when the byte is not one.
fn hex_digit(byte: u8) -> Option<u8> {
    match byte {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        b'A'..=b'F' => Some(byte - b'A' + 10),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn temp_dir(label: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("tricky-bootstrap-{label}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).expect("create temp dir");
        dir
    }

    fn config() -> RuntimeConfig {
        RuntimeConfig {
            keybox_chain_der: Vec::new(),
            keybox_private_key: Vec::new(),
            os_version: crate::surgeon::DEFAULT_OS_VERSION,
            os_patch: None,
            vendor_patch: None,
            boot_patch: None,
            boot_key: vec![0u8; 32],
            boot_hash: Vec::new(),
        }
    }

    #[test]
    fn hex_round_trips_and_rejects_junk() {
        assert_eq!(from_hex("00ff10").expect("valid"), vec![0x00, 0xff, 0x10]);
        assert_eq!(from_hex(""), None);
        assert_eq!(from_hex("abc"), None, "odd length");
        assert_eq!(from_hex("zz"), None, "not a hex digit");
    }

    #[test]
    fn the_report_overrides_the_defaults() {
        let mut config = config();
        apply_tee_status(
            &mut config,
            "boot_key=0102\nboot_hash=ff\nos_version=150000\nkeymaster_version=300\n",
        );
        assert_eq!(config.boot_key, vec![0x01, 0x02]);
        assert_eq!(config.boot_hash, vec![0xff]);
        assert_eq!(config.os_version, 150_000);
    }

    #[test]
    fn a_degenerate_report_keeps_the_defaults() {
        let mut config = config();
        apply_tee_status(
            &mut config,
            // An all-zero digest is what a field that failed to parse decodes to, and a zero OS
            // version would be stamped into every record. Both must be ignored.
            "boot_key=0000\nboot_hash=zz\nos_version=0\ngarbage line\n",
        );
        assert_eq!(config.boot_key, vec![0u8; 32]);
        assert!(config.boot_hash.is_empty());
        assert_eq!(config.os_version, crate::surgeon::DEFAULT_OS_VERSION);
    }

    #[test]
    fn a_missing_keybox_installs_nothing() {
        let dir = temp_dir("no-keybox");
        assert!(load(&dir).is_none());
        assert!(!install(&dir));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn the_persisted_boot_key_is_only_a_fallback() {
        let dir = temp_dir("boot-key");
        std::fs::write(dir.join(BOOT_KEY_FILE), "0a0b0c").expect("write");
        // Without a keybox there is no config at all.
        assert!(load(&dir).is_none());
        // The reader itself rejects a placeholder.
        assert_eq!(
            read_hex_file(&dir.join(BOOT_KEY_FILE)),
            Some(vec![10, 11, 12])
        );
        std::fs::write(dir.join(BOOT_KEY_FILE), "000000").expect("write");
        assert_eq!(read_hex_file(&dir.join(BOOT_KEY_FILE)), None);
        let _ = std::fs::remove_dir_all(&dir);
    }
}
